'use client';

import { Download, FileText } from 'lucide-react';
import { useState } from 'react';
import { AppPageShell } from '@/components/app-page-shell';

const reports = [
  { title: 'Monthly cashflow', detail: 'Income, spending, and net movement in one snapshot.', kind: 'Finance summary' },
  { title: 'Net worth trend', detail: 'Portfolio, assets, liabilities, and growth velocity.', kind: 'Wealth view' },
  { title: 'Budget adherence', detail: 'Category performance across this month.', kind: 'Planning' },
  { title: 'Tax-ready timeline', detail: 'Income events and investment gains with context.', kind: 'Tax readiness' },
];

export default function ReportsPage() {
  const [exported, setExported] = useState('');
  function exportReport(title: string) {
    const content = `${title}\nGenerated by FinTwin\n\nThis report is ready for your review.`;
    const url = URL.createObjectURL(new Blob([content], { type: 'text/plain' }));
    const anchor = document.createElement('a');
    anchor.href = url;
    anchor.download = `${title.toLowerCase().replaceAll(' ', '-')}.txt`;
    anchor.click();
    URL.revokeObjectURL(url);
    setExported(title);
  }
  return (
    <AppPageShell eyebrow="Signals" title="Reports" subtitle="Turn data into decisions with clear, spend-aware reporting." actionLabel="Export report">
      <section className="stats-grid">
        {reports.map((report) => (
          <div key={report.title} className="metric-card">
            <div className="metric-head">
              <div className="metric-icon"><FileText size={16} /></div>
              <span className="tag">{report.kind}</span>
            </div>
            <strong>{report.title}</strong>
            <small>{report.detail}</small>
            <button className="ghost-button compact-button" type="button" onClick={() => exportReport(report.title)}>
              <Download size={13} />
              {exported === report.title ? 'Downloaded' : 'Export'}
            </button>
          </div>
        ))}
      </section>
    </AppPageShell>
  );
}
